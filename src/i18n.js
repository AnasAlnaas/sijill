const DICTS = { ar, en };
let lang = 'ar';
let rules = new Intl.PluralRules('ar');

export function setLang(l) {
  lang = DICTS[l] ? l : 'ar';
  rules = new Intl.PluralRules(lang);
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  let s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (s && typeof s === 'object' && 'n' in vars) {
    s = s[rules.select(vars.n)] ?? s.other ?? s.many ?? '';
  }
  if (typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    const v = vars[k];
    if (v == null) return '';
    return typeof v === 'number' ? num(v) : String(v);
  });
}

export function markerName(shape) {
  return shape ? t('markerNames')[shape] : t('noMarker');
}
